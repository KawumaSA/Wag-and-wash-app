create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  booking_date date not null,
  start_minute smallint not null,
  service_id text not null check (service_id in ('bath', 'groom', 'nails')),
  service_duration_min smallint not null check (service_duration_min > 0),
  service_price numeric(8, 2) not null check (service_price >= 0),
  name text not null,
  phone text not null,
  email text,
  access_code_hash text,
  booking_email_consent boolean not null default false,
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid', 'initializing', 'pending', 'paid', 'expired', 'refunded')),
  payment_provider text,
  paypal_order_id text,
  paypal_capture_id text,
  payment_confirmation_email_sent boolean not null default false,
  payment_expires_at timestamptz,
  dog text not null,
  breed text not null default '',
  notes text not null default '',
  sms_consent boolean not null default false,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'completed', 'cancelled', 'no_show')),
  deposit_amount numeric(8, 2) not null default 25,
  paid numeric(8, 2) not null default 0,
  refunded boolean not null default false,
  created_at timestamptz not null default now(),
  constraint bookings_appointment_no_overlap
    exclude using gist (
      tsrange(
        booking_date + start_minute * interval '1 minute',
        booking_date + (start_minute + service_duration_min) * interval '1 minute',
        '[)'
      ) with &&
    )
    where (status in ('pending', 'confirmed'))
);

